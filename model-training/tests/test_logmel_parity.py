"""Python log-mel == Kotlin LogMel, on golden fixtures written by the Kotlin test.

Fixtures: tests/fixtures/logmel/*.json at the repo root, generated by
audio-ai/android/src/test/kotlin/com/kernel/audio_ai/LogMelGoldenFixtureTest.kt
(`cd audio-ai/example/android && ./gradlew :audio_ai:testDebugUnitTest`).

Tolerance: max |python - kotlin| <= 2e-6 nats on every value (ATOL), i.e.
about 2 float32 ulps at the largest magnitudes in the fixtures (|x| < 14).
Both sides compute in float64 and round to float32; the only possible
differences are the FFT algorithm (radix-2 vs pocketfft) and summation order,
~1e-12 relative before the log, which can at most flip the last float32 bit.
Observed on 2026-10-10: bit-exact (0 ulps) on both fixtures.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pytest

from kernel_train.logmel import PROVISIONAL, LogMel, LogMelConfig, frame_count, mel_weights, pcm16_to_float

REPO = Path(__file__).resolve().parents[2]
FIXTURES = REPO / "tests" / "fixtures" / "logmel"
ATOL = 2e-6

FIXTURE_FILES = sorted(FIXTURES.glob("*.json"))


def _load(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def _config(d: dict) -> LogMelConfig:
    c = d["config"]
    return LogMelConfig(
        sample_rate=int(c["sample_rate"]),
        n_fft=int(c["n_fft"]),
        win_length=int(c["win_length"]),
        hop_length=int(c["hop_length"]),
        n_mels=int(c["n_mels"]),
        f_min=float(c["f_min"]),
        f_max=float(c["f_max"]),
        log_offset=float(c["log_offset"]),
        power=float(c["power"]),
    )


def regenerate_signal(rate: int, count: int) -> np.ndarray:
    """Python copy of LogMelGoldenFixtureTest.signal (deterministic, no RNG)."""
    seconds = count / rate
    n = np.arange(count)
    t = n / rate
    sine = 0.25 * np.sin(2 * np.pi * 440.0 * t)
    chirp = 0.2 * np.sin(2 * np.pi * (100.0 * t + (7000.0 - 100.0) / (2.0 * seconds) * t * t))
    k = n % 1234
    click = 0.3 * np.exp(-k / 40.0) * np.sin(2 * np.pi * 2500.0 * k / rate)
    lcg = np.empty(count, dtype=np.int64)
    state = 12345
    for i in range(count):
        state = (state * 1103515245 + 12345) & 0x7FFFFFFF
        lcg[i] = state
    noise = 0.05 * (2.0 * lcg / 2147483648.0 - 1.0)
    x = sine + chirp + click + noise
    gap = (n >= count // 2) & (n < count // 2 + rate // 10)
    x[gap] = 0.0
    # Kotlin roundToInt == floor(x + 0.5)
    return np.clip(np.floor(x * 32768.0 + 0.5), -32768, 32767).astype(np.int16)


def test_fixtures_exist():
    assert FIXTURE_FILES, f"no fixtures in {FIXTURES}; run the Kotlin LogMelGoldenFixtureTest first"
    names = {p.stem for p in FIXTURE_FILES}
    assert "provisional_2s" in names


@pytest.mark.parametrize("path", FIXTURE_FILES, ids=lambda p: p.stem)
def test_python_logmel_matches_kotlin(path: Path):
    d = _load(path)
    cfg = _config(d)
    pcm = np.asarray(d["pcm16"], dtype=np.int16)
    expected = np.asarray(d["logmel"], dtype=np.float32).reshape(d["frames"], d["n_mels"])

    assert frame_count(pcm.size, cfg) == d["frames"]
    got = LogMel(cfg).compute(pcm16_to_float(pcm))
    assert got.shape == expected.shape
    err = np.abs(got.astype(np.float64) - expected.astype(np.float64))
    assert float(err.max()) <= ATOL, f"max abs error {err.max():.3e} nats at {np.unravel_index(err.argmax(), err.shape)}"
    # The floor (digital silence) must be exactly ln(offset) on both sides.
    floor = np.float32(math.log(cfg.log_offset))
    assert np.array_equal(got == floor, expected == floor)


@pytest.mark.parametrize("path", FIXTURE_FILES, ids=lambda p: p.stem)
def test_signal_formula_is_reproducible(path: Path):
    """The fixture input is a fixed formula; Python reproduces it to within 1 LSB."""
    d = _load(path)
    pcm = np.asarray(d["pcm16"], dtype=np.int16)
    regen = regenerate_signal(int(d["config"]["sample_rate"]), pcm.size)
    assert int(np.abs(regen.astype(np.int32) - pcm.astype(np.int32)).max()) <= 1


def test_provisional_matches_kotlin_constants():
    # Mirrors LogMelTest.provisionalConfigValues.
    assert PROVISIONAL == LogMelConfig(16000, 512, 400, 160, 64, 125.0, 7500.0, 0.001, 1.0)
    assert frame_count(32000, PROVISIONAL) == 198
    assert frame_count(399, PROVISIONAL) == 0
    assert frame_count(400, PROVISIONAL) == 1
    assert frame_count(560, PROVISIONAL) == 2


def test_filterbank_matches_kotlin_invariants():
    w = mel_weights(PROVISIONAL)
    assert w.shape == (64, 257)
    assert np.all(w[:, 0] == 0.0)
    assert np.all((w >= 0.0) & (w <= 1.0))
    assert np.all(w.max(axis=1) > 0.0)


def test_silence_is_log_offset_everywhere():
    out = LogMel(PROVISIONAL).compute(np.zeros(16000, dtype=np.float32))
    assert np.all(out == np.float32(math.log(0.001)))
